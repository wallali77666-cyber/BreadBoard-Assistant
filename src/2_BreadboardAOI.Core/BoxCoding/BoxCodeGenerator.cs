    }

    private static void AddPinDef(StringBuilder sb, HashSet<string> pinDefs, string macroName, string pinValue)
    {
        if (pinDefs.Add(macroName))
        {
            sb.AppendLine($"#define {macroName} {pinValue}");
        }
    }

    private static string CleanPin(string? pin)
    {
        if (string.IsNullOrWhiteSpace(pin))
            return "2";

        string p = pin.Trim();
        if (p.StartsWith("Pin ", StringComparison.OrdinalIgnoreCase))
            p = p[4..].Trim();
        if (p.StartsWith("GPIO", StringComparison.OrdinalIgnoreCase))
        {
            var parts = p.Split(' ');
            return parts.Length > 1 ? parts[1] : p[4..];
        }
        if (p.StartsWith("D", StringComparison.OrdinalIgnoreCase) && p.Length > 1 && char.IsDigit(p[1]))
            return p[1..];
        return p;
    }

    private static int ExtractPinNumber(string? pin)
    {
        if (string.IsNullOrWhiteSpace(pin))
            return 2;

        var digits = new string(pin.Where(char.IsDigit).ToArray());
        return int.TryParse(digits, out int val) ? val : 2;
    }

