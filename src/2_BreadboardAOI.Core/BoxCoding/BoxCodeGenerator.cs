    /// <summary>Auto-detects components on the breadboard circuit and generates matching code blocks.</summary>
        public static List<BoxBlockItem> AutoDetectFromCircuit(
        IEnumerable<DraftPart> parts,
        MicrocontrollerBoardType boardType)
    {
        var list = new List<BoxBlockItem>();
        var partList = parts.ToList();

        // 1. Startup Block
        list.Add(new BoxBlockItem
        {
            Kind = BoxBlockKind.WhenStarted,
            Category = BoxBlockCategory.Events,
            Title = "When Board Starts",
            Icon = "🚀",
            AccentHexColor = "#E67E22",
            BackgroundHexColor = "#3E2723",
            Description = "Configures pin directions, serial telemetry @ 115200 baud, and hardware peripherals."
        });

        // Check hardware presences
        bool hasLcd = partList.Any(p => (p.Value ?? p.SymbolId ?? "").Contains("LCD", StringComparison.OrdinalIgnoreCase) ||
                                        (p.Value ?? p.SymbolId ?? "").Contains("1602", StringComparison.OrdinalIgnoreCase) ||
                                        (p.Value ?? p.SymbolId ?? "").Contains("HD44780", StringComparison.OrdinalIgnoreCase));

        bool hasDht = partList.Any(p => p.Kind == ComponentKind.Sensor && (p.Value ?? p.SymbolId ?? "").Contains("DHT", StringComparison.OrdinalIgnoreCase));
        bool hasUltra = partList.Any(p => p.Kind == ComponentKind.Sensor && ((p.Value ?? p.SymbolId ?? "").Contains("HC", StringComparison.OrdinalIgnoreCase) ||
                                                                            (p.Value ?? p.SymbolId ?? "").Contains("SR04", StringComparison.OrdinalIgnoreCase) ||
                                                                            (p.Value ?? p.SymbolId ?? "").Contains("ULTRA", StringComparison.OrdinalIgnoreCase)));
        bool hasMpu = partList.Any(p => p.Kind == ComponentKind.Sensor && ((p.Value ?? p.SymbolId ?? "").Contains("MPU", StringComparison.OrdinalIgnoreCase) ||
                                                                           (p.Value ?? p.SymbolId ?? "").Contains("6050", StringComparison.OrdinalIgnoreCase)));
        bool hasGas = partList.Any(p => p.Kind == ComponentKind.Sensor && ((p.Value ?? p.SymbolId ?? "").Contains("MQ", StringComparison.OrdinalIgnoreCase) ||
                                                                           (p.Value ?? p.SymbolId ?? "").Contains("GAS", StringComparison.OrdinalIgnoreCase)));
        bool hasPot = partList.Any(p => p.Kind == ComponentKind.Potentiometer);
        bool hasLed = partList.Any(p => p.Kind == ComponentKind.Led);
        bool hasBuzzer = partList.Any(p => p.Kind == ComponentKind.Buzzer);
        bool hasButton = partList.Any(p => p.Kind == ComponentKind.PushButton);

        // If LCD is on board, initialize it in the setup sequence
        if (hasLcd)
        {
            list.Add(new BoxBlockItem
            {
                Kind = BoxBlockKind.LcdInitI2c,
                Category = BoxBlockCategory.Displays,
                Title = "Init LCD 1602 I2C (0x27)",
                ModelName = "LCD1602 I2C",
                Icon = "🖥️",
                AccentHexColor = "#06B6D4",
                BackgroundHexColor = "#083344",
                LcdI2cAddress = "0x27",
                IsCircuitMatched = true,
                Description = "Initializes 16x2 HD44780 LCD via PCF8574 I2C backpack and enables backlight."
            });
        }

        // 2. Main Forever Loop
        list.Add(new BoxBlockItem
        {
            Kind = BoxBlockKind.ForeverLoop,
            Category = BoxBlockCategory.Events,
            Title = "Forever Loop",
            Icon = "🔁",
            AccentHexColor = "#F39C12",
            BackgroundHexColor = "#451A03",
            Description = "Continuous main control loop repeating at fixed refresh cadence."
        });

        // 3. Sensor Reading Blocks
        if (hasDht)
        {
            list.Add(new BoxBlockItem
            {
                Kind = BoxBlockKind.ReadDhtSensor,
                Category = BoxBlockCategory.Sensors,
                Title = "Read DHT11 Sensor",
                ModelName = "DHT11",
                Icon = "🌡️",
                AccentHexColor = "#00ACC1",
                BackgroundHexColor = "#006064",
                IsCircuitMatched = true,
                Pin1 = boardType == MicrocontrollerBoardType.Esp32DevKitV1 ? "GPIO 4" : "D2",
                Description = "Reads ambient temperature (°C) and relative humidity (%)."
            });
        }

        if (hasUltra)
        {
            list.Add(new BoxBlockItem
            {
                Kind = BoxBlockKind.ReadUltrasonic,
                Category = BoxBlockCategory.Sensors,
                Title = "Read HC-SR04 Ultrasonic",
                ModelName = "HC-SR04",
                Icon = "📡",
                AccentHexColor = "#0288D1",
                BackgroundHexColor = "#0D47A1",
                IsCircuitMatched = true,
                Pin1 = boardType == MicrocontrollerBoardType.Esp32DevKitV1 ? "GPIO 5" : "D9",
                Pin2 = boardType == MicrocontrollerBoardType.Esp32DevKitV1 ? "GPIO 18" : "D10",
                Description = "Measures distance to obstacle in cm."
            });
        }

        if (hasMpu)
        {
            list.Add(new BoxBlockItem
            {
                Kind = BoxBlockKind.ReadMpu6050,
                Category = BoxBlockCategory.Sensors,
                Title = "Read MPU-6050 IMU",
                ModelName = "MPU-6050",
                Icon = "🔄",
                AccentHexColor = "#3949AB",
                BackgroundHexColor = "#1A237E",
                IsCircuitMatched = true,
                Description = "Reads 6-axis acceleration and gyroscope data over I2C."
            });
        }

        if (hasGas)
        {
            list.Add(new BoxBlockItem
            {
                Kind = BoxBlockKind.ReadGasSensor,
                Category = BoxBlockCategory.Sensors,
                Title = "Read MQ-2 Gas/Smoke",
                ModelName = "MQ-2",
                Icon = "💨",
                AccentHexColor = "#FB8C00",
